import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  baselineOptions,
  sources as cases,
} from '../../scripts/qualify-jsconfuser-vm/config.mjs'

// Encoded VM fixtures are not committed: each is regenerated from the recipe its
// fixture directory already records (source, options, seed) and written to the path
// the tests read. This module reads those records; materialize-fixtures.js writes
// the files, and test/vm/.gitignore lists exactly the paths it owns.

const testRoot = fileURLToPath(new URL('./', import.meta.url))
const decoderRoot = fileURLToPath(new URL('../../', import.meta.url))
const fixtureRoot = path.join(testRoot, 'jsconfuser-vm/fixtures')
const walk = (directory) =>
  fs
    .readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) =>
      entry.isDirectory()
        ? walk(path.join(directory, entry.name))
        : [path.join(directory, entry.name)],
    )
const read = (file) => fs.readFileSync(file, 'utf8')
const json = (file) => JSON.parse(read(file))
const full = (options = {}) => ({ ...baselineOptions, ...options })

export function fixtureRecipes() {
  const recipes = new Map()
  const put = (file, sourceFile, options, seed = 1, listing = false) => {
    // Some records also list the source a case was built from; it is input, never output.
    if (recipes.has(file) || /(^|[.\/])(source|src)\.js$/.test(file)) return
    const source = sourceFile.startsWith('case:')
      ? cases[sourceFile.slice(5)]
      : read(sourceFile)
    recipes.set(file, {
      file,
      sourcePath: sourceFile.startsWith('case:')
        ? sourceFile
        : path.relative(decoderRoot, sourceFile),
      source,
      options: full(options),
      seed,
      listing,
    })
  }
  for (const file of walk(fixtureRoot)) {
    const directory = path.dirname(file),
      base = path.basename(file),
      at = (name) => path.join(directory, name)
    if (/^qualification(-\d+)?\.json$/.test(base)) {
      const record = json(file),
        suffix = base.slice('qualification'.length, -'.json'.length)
      put(at(`encoded${suffix}.js`), at('source.js'), record.options, record.seed)
    } else if (base === 'generation.json') {
      const record = json(file)
      for (const cell of Object.keys(record.cells ?? {})) {
        const options = record.cellOptions?.[cell] ?? {},
          cellDirectory = fs.existsSync(at(cell)) ? at(cell) : directory
        put(
          path.join(cellDirectory, 'encoded.js'),
          path.join(cellDirectory, 'source.js'),
          { ...record.vmEncoder?.options, ...options.options },
          options.seed,
        )
      }
      if (!record.outerEncoder)
        for (const [name, entry] of Object.entries(record.files ?? {}))
          put(at(name), at(entry.source ?? 'source.js'), entry.options, entry.seed, entry.listing)
      // The two-encoder fixture's VM-only stage, listing kept (the outer encoder read it).
      if (record.outerEncoder && record.randomness)
        put(at('vm-only.js'), at('source.js'), record.vmEncoder.options, record.randomness.seed, true)
    } else if (base === 'provenance.json') {
      const record = json(file)
      for (const row of record.records ?? [])
        put(
          at(row.encoded),
          row.source && fs.existsSync(at(row.source)) ? at(row.source) : `case:${row.case}`,
          row.options,
          row.seed,
        )
      for (const row of record.fixtureRows ?? []) {
        const [caseName, , seed] = row.producer.id.split('--')
        put(at(row.path), `case:${caseName}`, row.producer.options, Number(seed))
      }
    } else if (base === 'manifest.json' && directory.endsWith('/readability')) {
      const record = json(file)
      for (const name of record.cases)
        // The readability inputs keep the encoder's leading listing comment.
        put(path.join(directory, name, 'encoded.js'), path.join(directory, name, 'source.js'), record.options, 1, true)
    } else if (
      base === 'source.js' &&
      directory.includes('/corpus/') &&
      !directory.includes('/negative/')
    ) {
      put(at('encoded.js'), file, {})
    }
  }
  return [...recipes.values()].sort((a, b) => a.file.localeCompare(b.file))
}

export const ignoreFile = path.join(testRoot, '.gitignore')
export function ignoreList(recipes = fixtureRecipes()) {
  return (
    '# Generated by test/vm/materialize-fixtures.js from the recipes in fixture-recipes.js;\n' +
    '# rewrite with `node test/vm/materialize-fixtures.js --write-ignore`.\n' +
    recipes.map(({ file }) => `/${path.relative(testRoot, file)}`).join('\n') +
    '\n'
  )
}
