// Generated cells: each suite commits source, profile and seed; the encoded input
// is generated by the pinned encoder into an ignored cache and never committed.
// A cell's cache key covers everything its bytes depend on, so a changed encoder
// pin, dependency lock, Node or JDK major, source, option vector or seed is a miss.

const testRoot = fileURLToPath(new URL('../', import.meta.url))
// Each suite folder owns its definition (suite.js); this collects them for what crosses suites.
const suiteRoot = path.join(testRoot, 'generated-cells')
export const suites = await Promise.all(
  fs
    .readdirSync(suiteRoot)
    .sort()
    .map(
      async (name) =>
        (await import(pathToFileURL(path.join(suiteRoot, name, 'suite.js')))).default,
    ),
)
export const cacheRoot = path.join(decoderRoot, 'sandbox-tests/vm-cells')

const sha256 = (value) => crypto.createHash('sha256').update(value).digest('hex')
const nodeMajor = process.versions.node.split('.')[0]
function jdkMajor() {
  if (!javaRoot) return null
  const release = fs.readFileSync(path.join(javaRoot, 'release'), 'utf8')
  return /JAVA_VERSION="(\d+)/.exec(release)?.[1] ?? null
}

const lockDigest = sha256(fs.readFileSync(encoderLock))
// The cache key of one encoding: everything its bytes depend on.
export function cellKey({ source, options, seed }) {
  return sha256(
    JSON.stringify([
      PIN,
      lockDigest,
      nodeMajor,
      options.minify ? jdkMajor() : null,
      sha256(source),
      Object.entries(options).sort(),
      seed,
    ]),
  )
}

export function profileOptions(profile) {
  const options = { ...baselineOptions }
  if (profile === 'baseline') return options
  for (const part of profile.split('+')) {
    const [name, value] = part.split('=')
    if (!(name in baselineOptions)) throw new Error(`Unknown option ${name}`)
    options[name] = value === undefined ? true : Number(value)
  }
  return options
}

// A program lives in sources/<name>, or in a fixture directory of that name until the fixture goes.
function sourceDirectories(root, found = new Map()) {
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    const directory = path.join(root, entry.name)
    if (fs.existsSync(path.join(directory, 'source.js')))
      if (!found.has(entry.name)) found.set(entry.name, directory)
    sourceDirectories(directory, found)
  }
  return found
}
const directories = new Map([
  ...sourceDirectories(path.join(testRoot, 'fixtures')),
  ...sourceDirectories(path.join(testRoot, 'sources')),
])

export function readSource(name) {
  const directory = directories.get(name)
  const oraclePath = path.join(directory, 'oracle.json')
  return {
    source: fs.readFileSync(path.join(directory, 'source.js'), 'utf8'),
    oracle: fs.existsSync(oraclePath)
      ? JSON.parse(fs.readFileSync(oraclePath, 'utf8'))
      : {},
  }
}

// Fresh seeds are drawn per run (VM_FRESH_SEEDS=N) and recorded in each cell.json,
// so a failing fresh cell can be regenerated and added to the fixed set.
export function freshSeeds(count = Number(process.env.VM_FRESH_SEEDS ?? 0)) {
  return Array.from({ length: count }, () => crypto.randomInt(1, 2 ** 31))
}

// One case of a suite's test file, for one source, profile and seed.
function makeCell(suite, file, name, profile, seed, fresh = false) {
  const { source, oracle } = readSource(name)
  const options = profileOptions(profile)
  const id = `${suite}/${file}/${name}/${profile}/${seed}`
  return {
    id,
    suite,
    file,
    name,
    profile,
    seed,
    fresh,
    options,
    source,
    oracle,
    expect: 'accepted',
    directory: path.join(
      cacheRoot,
      cellKey({ source, options, seed }),
    ),
  }
}

export function expandCells(fresh = []) {
  return suites.flatMap(({ name: suite, files }) =>
    Object.entries(files).flatMap(([file, cases]) =>
      cases.flatMap(({ sources, profile, seeds }) =>
        sources.flatMap((name) => [
          ...seeds.map((seed) => makeCell(suite, file, name, profile, seed)),
          ...fresh.map((seed) => makeCell(suite, file, name, profile, seed, true)),
        ]),
      ),
    ),
  )
}

// The same source and seed under randomized opcodes alone: what a stage is compared with.
export function plainCell(cell) {
  return makeCell('plain', 'control', cell.name, 'randomizeOpcodes', cell.seed)
}

// The encoder checkout must be the pinned commit with a clean worktree; a missing
// default checkout is cloned and installed from the committed lock.
export function ensureEncoder() {
  if (!process.env.JSCONFUSER_VM_ENCODER && !fs.existsSync(encoderRoot))
    fetchEncoder()
  const git = (args) =>
    execFileSync('git', args, { cwd: encoderRoot, encoding: 'utf8' }).trim()
  if (git(['rev-parse', 'HEAD']) !== PIN)
    throw new Error(`Encoder checkout ${encoderRoot} is not at ${PIN}`)
  if (git(['status', '--porcelain']))
    throw new Error(`Encoder checkout ${encoderRoot} is not clean`)
}

// The emitted program starts with the encoder's instruction-listing comment; the
// qualifier drops those leading line comments, and so do the cells.
const withoutListing = (raw) => {
  const lines = raw.split('\n')
  return lines.slice(lines.findIndex((line) => !line.startsWith('//'))).join('\n')
}

async function generate(cell) {
  fs.mkdirSync(cell.directory, { recursive: true })
  const journalPath = path.join(cell.directory, 'generation.ndjson')
  fs.writeFileSync(journalPath, '')
  const run = await runWorker(
    {
      action: 'generate',
      seed: cell.seed,
      source: cell.source,
      options: cell.options,
      journalPath,
    },
    65000,
  )
  const raw = run.result?.raw
  const record = {
    cell: cell.id ?? null,
    source: cell.sourcePath ?? cell.name,
    profile: cell.profile ?? null,
    options: cell.options,
    seed: cell.seed,
    encoderPin: PIN,
    toolchain: { node: process.versions.node, jdk: cell.options.minify ? jdkMajor() : null },
    generation: typeof raw === 'string' ? 'ok' : 'failed',
    error: typeof raw === 'string' ? null : JSON.stringify(run).slice(0, 2000),
  }
  if (typeof raw === 'string') {
    fs.writeFileSync(path.join(cell.directory, 'raw.js'), raw)
    fs.writeFileSync(path.join(cell.directory, 'encoded.js'), withoutListing(raw))
  }
  fs.writeFileSync(path.join(cell.directory, 'source.js'), cell.source)
  fs.writeFileSync(path.join(cell.directory, 'cell.json'), JSON.stringify(record))
}

export async function generateMissing(cells, concurrency = Math.max(1, os.availableParallelism() - 1)) {
  // A failed generation is not cached: a timeout or an absent JDK is retried.
  const missing = cells.filter((cell) => {
    const recordPath = path.join(cell.directory, 'cell.json')
    return (
      !fs.existsSync(recordPath) ||
      JSON.parse(fs.readFileSync(recordPath, 'utf8')).generation !== 'ok'
    )
  })
  if (!missing.length) return 0
  ensureEncoder()
  let next = 0
  await Promise.all(
    Array.from({ length: Math.min(concurrency, missing.length) }, async () => {
      while (next < missing.length) await generate(missing[next++])
    }),
  )
  return missing.length
}

export function readCell(cell) {
  const record = JSON.parse(fs.readFileSync(path.join(cell.directory, 'cell.json'), 'utf8'))
  const encodedPath = path.join(cell.directory, 'encoded.js')
  return {
    record,
    encoded: fs.existsSync(encodedPath) ? fs.readFileSync(encodedPath, 'utf8') : null,
  }
}

export function writeResult(cell, result, decoded) {
  if (decoded !== null)
    fs.writeFileSync(path.join(cell.directory, 'decoded.js'), decoded)
  fs.writeFileSync(path.join(cell.directory, 'result.json'), JSON.stringify(result))
}
